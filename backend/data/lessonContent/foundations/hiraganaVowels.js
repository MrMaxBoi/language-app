const characterFocus = ({ id, conceptId, title, character, romanization, soundCue, soundNote }) => ({
  id,
  type: "character_focus",
  conceptId,
  title,
  character,
  romanization,
  soundCue,
  soundNote,
  audioText: character,
});

const characterTrace = ({ id, conceptId, character, romanization, tracingKey }) => ({
  id,
  type: "character_trace",
  conceptId,
  title: `Trace ${character}`,
  character,
  romanization,
  tracingKey,
});

const wordContext = ({
  id,
  conceptIds,
  illustrationKey,
  illustrationAlt,
  japanese,
  meaning,
  segments,
}) => ({
  id,
  type: "word_context",
  conceptIds,
  illustrationKey,
  illustrationAlt,
  japanese,
  meaning,
  audioText: japanese,
  segments,
});

